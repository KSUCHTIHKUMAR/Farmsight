const DICT: Record<Lang, Record<Key, string>> = { en: EN, te: TE }

interface Ctx {
  t: (k: Key) => string
}

const LangContext = createContext<Ctx>({ t: (k) => EN[k] })

export function LangProvider({ children }: { children: ReactNode }) {
  useEffect(() => {
    document.documentElement.lang = 'en'
    try {
      localStorage.removeItem('farmsight.lang')
    } catch {
      /* storage unavailable */
    }
  }, [])
  const value: Ctx = { t: (k) => DICT.en[k] }
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>
}

export function useT() {
  return useContext(LangContext)
}

